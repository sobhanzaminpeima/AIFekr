const DICTIONARIES = { en: en.crm, fa: fa.crm, de: (de as typeof en).crm, tr: tr.crm };
const COLUMN: Record<Lang, number> = { fa: 0, en: 1, de: 2, tr: 3 };

export function crmCopy(lang: Lang) {
  const column = COLUMN[lang] ?? 1;
  return {
    dict: DICTIONARIES[lang] ?? en.crm,
    strings: Object.fromEntries(CRM_STRINGS.map((r) => [r[1], r[column]])),
    labels: Object.fromEntries(Object.entries(CRM_LABELS).map(([table, entries]) => [table, Object.fromEntries(Object.entries(entries).map(([k, r]) => [k, r[column]]))])),
  };
}
