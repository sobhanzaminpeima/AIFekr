const COL: Record<Lang, number> = { fa: 0, en: 1, de: 2, tr: 3 };
// Two classic strings share one English text ("Queued": the status and the progress stage);
// the later one is keyed "<English> · 2" so each keeps its own wording.
const keyOf = (row: Four, i: number) => (VOICE_STRINGS.findIndex((r) => r[1] === row[1]) < i ? `${row[1]} · 2` : row[1]);
export function voiceCopy(lang: Lang) {
  return {
    strings: Object.fromEntries(VOICE_STRINGS.map((row, i) => [keyOf(row, i), row[COL[lang]]])) as Record<string, string>,
    errors: Object.fromEntries(Object.entries(VOICE_ERRORS).map(([code, row]) => [code, row[COL[lang]]])) as Record<string, string>,
  };
}
